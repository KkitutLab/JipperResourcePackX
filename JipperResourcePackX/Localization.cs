    public static string Get(string key) {
        if (string.IsNullOrEmpty(key)) return string.Empty;
        bool isKorean = RDString.language == SystemLanguage.Korean;
        var dict = isKorean ? Korean : English;
        if (dict.TryGetValue(key, out var val)) return val;
        if (!isKorean && Korean.TryGetValue(key, out val)) return val;
        if (isKorean && English.TryGetValue(key, out val)) return val;
        return key;
    }
